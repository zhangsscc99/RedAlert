#!/usr/bin/env bash
# This Node build lacks TypeScript type-stripping, so `node --test` can't run
# .ts files. Bundle each *.test.ts into a runnable *.test.js next to it
# (game code inlined, node builtins external). Output is committed so that
# `node --test client/src/game/` works without a build step.
set -euo pipefail
cd "$(dirname "$0")/../client"

for f in src/game/*.test.ts src/input/*.test.ts src/render/*.test.ts; do
  npx esbuild "$f" --bundle --platform=node --format=esm --outfile="${f%.ts}.js"
done

# Node --test <dir> resolves the directory to index.js rather than scanning
# for *.test.js, so keep a shim per dir that registers every test bundle.
for d in src/game src/input src/render; do
  {
    echo '// Test entry: makes `node --test client/'"${d}"'/` work on Node builds'
    echo '// without directory scanning — importing this file registers all tests.'
    echo '// GENERATED by scripts/build-tests.sh — do not edit by hand.'
    for f in "$d"/*.test.js; do
      printf 'import "./%s";\n' "$(basename "$f")"
    done
  } >"$d/index.js"
done
echo "built test bundles: src/{game,input,render}/*.test.js"
